/** 相邻字母墨迹左边界之间的距离；斜体字母互相交错，所以比前一个字母窄 */
const ADVANCE: Record<string, number> = {
    mf: 8.0028,
    mp: 9.523,
    ff: 6.67866,
    pp: 8.8083, // 没有 pp 连字可量，沿用 m 与 p 的墨迹重叠量
};

const INK: PaintStyle = { fill: "#000" };

/** size 是 f 的全高；p 系没有升部、盒子只有 f 的这么高，不按此缩小就会被放大 1.26 倍 */
const P_WEIGHT = 0.79341;

function dynamic(name: string, velocity: number, description: string): SymbolDefinition {
    let dx = 0;
    const shapes = Array.from(name, (letter, index) => {
        const shape = { path: GLYPHS[letter], style: INK, dx };
        dx += ADVANCE[letter + name[index + 1]] ?? 0;
        return shape;
    });
    return {
        name,
        description,
        shapes,
        weight: name.includes("f") ? 1 : P_WEIGHT,
        onTimeState: state => { state.velocity = velocity; },
    };
}

